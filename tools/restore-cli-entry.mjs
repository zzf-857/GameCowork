// Reconstitute Bun's carved CJS factory as an executable CommonJS entry.
// The extracted source is not launched by this script; output is a generated test/build input.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isBuiltin } from 'node:module';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
function option(name, fallback) {
  const index = args.indexOf(name);
  if (index === -1) return fallback;
  if (!args[index + 1]) throw new Error(`${name} requires a value`);
  return path.resolve(args[index + 1]);
}
const sourceFile = option('--source', path.join(project, 'src/agent/cli-main.beautified.js'));
const outputFile = option('--output', 'F:/AI/AgentMake/temp/GameCowork/cli-recovery/cli-entry.cjs');
const original = fs.readFileSync(sourceFile, 'utf8');
const prefix = '// @bun @bytecode @bun-cjs';
if (!original.startsWith(prefix)) throw new Error('Unrecognized Bun CJS factory header');
const factory = '(function (exports, require, module, __filename, __dirname) {';
if (original.indexOf(factory) === -1 || original.indexOf(factory, original.indexOf(factory) + factory.length) !== -1) throw new Error('Expected one complete CJS factory');
const trimmed = original.trimEnd();
if (!trimmed.endsWith('});')) throw new Error('CJS factory footer is incomplete');
const body = trimmed.slice(prefix.length, -3);
const entry = '// Generated by tools/restore-cli-entry.mjs from the recovered Bun CJS factory.\n' + body + '})(exports, require, module, __filename, __dirname);\n';
fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, entry);
const modules = [...new Set([...original.matchAll(/require\(("[^"]*"|'[^']*')\)/g)].map(match => match[1].slice(1, -1)).filter(name => !isBuiltin(name) && name !== '%s'))];
console.log(JSON.stringify({ source: sourceFile, output: outputFile, bytes: Buffer.byteLength(entry), externalModules: modules }));
